// goal A3 (Aryan). Listens on tests.generated. See build-plan.md, Phase D.
import type { Skill } from '@pact/core';
import { must } from '@pact/core';

// Three real side effects: one issue per SOW line, a PR adding the generated specs to the booking
// repo, and an engineering baseline build (kind 'main') of main HEAD so coverage has something real to read.
export const handler: Skill<{ dealId: string; version: number }, void> = async ({ dealId, version }, ctx) => {
  const sow = must(ctx.store.getSow(dealId, version), `sow ${dealId} v${version}`);
  for (const line of sow.lines) {
    if (ctx.store.getIssueNumber(line.id)) continue; // dedupe, no GitHub search needed
    const n = await ctx.github.createIssue(`SOW ${line.id} ${line.title}`, `**Acceptance criterion:** ${line.criterion}\n\nTest: \`specs/${dealId}/${ctx.store.testIdFor(line.id)}.spec.ts\``);
    ctx.store.setIssueNumber(line.id, n);
    ctx.log.info(`issue #${n} for SOW ${line.id}`);
  }

  const tests = ctx.store.listAcceptanceTests(dealId);
  const files = await Promise.all(tests.map(async (t) => ({
    path: `specs/${dealId}/${t.id}.spec.ts`, content: await ctx.files.readSpec(dealId, t.id),
  })));
  if (files.length > 0) {
    const pr = await ctx.github.openPrWithFiles(`pact/specs-${dealId}-v${version}`, files,
      `Acceptance tests from SOW v${version}`, 'Generated by Pact from the approved SOW. One spec per SOW line.');
    ctx.log.info(`test PR #${pr} opened`);
  }

  const sha = await ctx.github.getHeadSha('main');
  const build = ctx.store.createBuild({ dealId, kind: 'main', ref: sha });
  await ctx.bus.emit('build.requested', { buildId: build.id });
};
